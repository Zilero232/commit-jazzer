// Writes the list of figlet fonts as a constant: `bun scripts/generate-fonts.ts` after upgrading figlet.
// The config schema validates `figletOptions.font` against it without reading the disk at import time;
// a test fails when the list and the installed figlet disagree.
import figlet from 'figlet';
import { writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';

const OUTPUT = new URL('../src/core/config/figlet-fonts.constants.ts', import.meta.url);

const fonts = figlet.fontsSync().sort((a, b) => a.localeCompare(b));

const source = `// Generated by scripts/generate-fonts.ts. Do not edit by hand.
export const FIGLET_FONTS = ${JSON.stringify(fonts)} as const;
`;

// Formatted like the rest of the code, so the prettier check passes on the generated file.
await writeFile(OUTPUT, await format(source, { ...(await resolveConfig(OUTPUT)), filepath: OUTPUT.pathname }));

console.log(`${fonts.length} figlet fonts written to ${OUTPUT.pathname}`);
