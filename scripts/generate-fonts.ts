// Writes the list of figlet fonts as a constant: `bun run generate-fonts` after upgrading figlet.
// The config schema validates `figletOptions.font` against it without reading the disk at import time;
// a test fails when the list and the installed figlet disagree.
import figlet from 'figlet';
import { writeFile } from 'node:fs/promises';

const OUTPUT = new URL('../src/core/config/figlet-fonts.constants.ts', import.meta.url);

const fonts = figlet.fontsSync().sort((a, b) => a.localeCompare(b));

await writeFile(
  OUTPUT,
  `// Generated by scripts/generate-fonts.ts. Do not edit by hand.\nexport const FIGLET_FONTS = ${JSON.stringify(fonts, null, 2)} as const;\n`
);

console.log(`${fonts.length} figlet fonts written to ${OUTPUT.pathname}`);
